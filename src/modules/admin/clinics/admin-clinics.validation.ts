// src/modules/admin/clinics/admin-clinics.validation.ts

import { z } from "zod";
import { workingHoursSchema } from "../../clinic-settings/clinic-settings.validation";

// ---------------------------------------------------------------------------
// Shared field rules (same limits as the clinic-side settings / doctor schemas)
// ---------------------------------------------------------------------------

const clinicName = z
  .string()
  .trim()
  .min(2, "Clinic name must be at least 2 characters")
  .max(100, "Clinic name must not exceed 100 characters");

const phone = z
  .string()
  .trim()
  .min(7, "Phone number must be at least 7 characters")
  .max(20, "Phone number must not exceed 20 characters")
  .regex(/^\+?[0-9\s\-().]+$/, "Invalid phone number format");

const clinicEmail = z
  .string()
  .trim()
  .toLowerCase()
  .email("Invalid email address")
  .max(100, "Email must not exceed 100 characters");

const address = z
  .string()
  .trim()
  .min(1, "Address cannot be empty")
  .max(255, "Address must not exceed 255 characters");

// Login email of a clinic user. Stored lowercase.
const loginEmail = z
  .string()
  .trim()
  .toLowerCase()
  .min(1, "Email is required")
  .email("Invalid email address");

const fullName = z
  .string()
  .trim()
  .min(2, "Full name must be at least 2 characters")
  .max(100, "Full name must be at most 100 characters");

const specialty = z
  .string()
  .trim()
  .min(2, "Specialty must be at least 2 characters")
  .max(100, "Specialty must not exceed 100 characters");

const bio = z.string().trim().max(1000, "Bio must not exceed 1000 characters");

const doctorAppointmentDuration = z
  .number()
  .int()
  .min(5, "Appointment duration must be at least 5 minutes")
  .max(240, "Appointment duration must not exceed 240 minutes");

// ---------------------------------------------------------------------------
// POST /admin/clinics — clinic + settings + its first doctor, in one request.
// The doctor's password is generated by the server, never supplied.
// ---------------------------------------------------------------------------

export const createClinicSchema = z.object({
  clinic: z.object({
    name: clinicName,
    phone: phone.optional(),
    email: clinicEmail.optional(),
    address: address.optional(),
  }),
  doctor: z.object({
    fullName,
    email: loginEmail,
    specialty,
    bio: bio.optional(),
  }),
  // Every field optional: omitted ones get the system defaults
  settings: z
    .object({
      workingHours: workingHoursSchema.optional(),
      maxPatientsPerDay: z.number().int().min(1).max(1000).optional(),
      appointmentDuration: z.number().int().min(5).max(480).optional(),
      gracePeriod: z.number().int().min(1).max(120).optional(),
      delayThreshold: z.number().int().min(1).max(240).optional(),
    })
    .optional(),
});

// ---------------------------------------------------------------------------
// GET /admin/clinics
// ---------------------------------------------------------------------------

export const listClinicsQuerySchema = z.object({
  search: z.string().trim().max(100).optional(),
  status: z.enum(["active", "inactive", "all"]).default("all"),
  page: z.coerce.number().int().min(1).default(1),
  limit: z.coerce.number().int().min(1).max(100).default(20),
});

// ---------------------------------------------------------------------------
// PATCH /admin/clinics/:id — null clears an optional field
// ---------------------------------------------------------------------------

export const updateClinicSchema = z
  .object({
    name: clinicName.optional(),
    phone: phone.nullable().optional(),
    email: clinicEmail.nullable().optional(),
    address: address.nullable().optional(),
  })
  .refine((d) => Object.keys(d).length > 0, {
    message: "At least one field must be provided for update",
  });

// PATCH /admin/clinics/:id/status
export const updateClinicStatusSchema = z.object({
  isActive: z.boolean(),
});

// ---------------------------------------------------------------------------
// POST /admin/clinics/:id/doctors — extra doctor for an existing clinic
// ---------------------------------------------------------------------------

export const addDoctorSchema = z.object({
  fullName,
  email: loginEmail,
  specialty,
  bio: bio.optional(),
  appointmentDuration: doctorAppointmentDuration.optional(),
  workingHours: workingHoursSchema.optional(),
  isBookable: z.boolean().optional(),
});

// ---------------------------------------------------------------------------
// Params
// ---------------------------------------------------------------------------

export const clinicIdParamSchema = z.object({
  id: z.string().uuid("Invalid clinic ID format"),
});

export const clinicUserParamSchema = z.object({
  id: z.string().uuid("Invalid clinic ID format"),
  userId: z.string().uuid("Invalid user ID format"),
});

export type CreateClinicInput = z.infer<typeof createClinicSchema>;
export type ListClinicsQuery = z.infer<typeof listClinicsQuerySchema>;
export type UpdateClinicInput = z.infer<typeof updateClinicSchema>;
export type AddDoctorInput = z.infer<typeof addDoctorSchema>;
