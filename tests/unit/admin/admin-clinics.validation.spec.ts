import {
  createClinicSchema,
  listClinicsQuerySchema,
  updateClinicSchema,
  updateClinicStatusSchema,
  addDoctorSchema,
  clinicIdParamSchema,
  clinicUserParamSchema,
} from "../../../src/modules/admin/clinics/admin-clinics.validation";

const validCreate = {
  clinic: { name: "Al Shifa Clinic" },
  doctor: {
    fullName: "Dr. Ahmed Hassan",
    email: "Ahmed@Example.com",
    specialty: "Cardiology",
  },
};

describe("createClinicSchema", () => {
  it("accepts the minimal payload and lowercases the doctor email", () => {
    const r = createClinicSchema.parse(validCreate);
    expect(r.doctor.email).toBe("ahmed@example.com");
  });

  it("requires both clinic and doctor", () => {
    expect(createClinicSchema.safeParse({ clinic: validCreate.clinic }).success).toBe(false);
    expect(createClinicSchema.safeParse({ doctor: validCreate.doctor }).success).toBe(false);
  });

  it("rejects a bad doctor email or a too-short clinic name", () => {
    expect(
      createClinicSchema.safeParse({
        ...validCreate,
        doctor: { ...validCreate.doctor, email: "nope" },
      }).success
    ).toBe(false);
    expect(
      createClinicSchema.safeParse({ ...validCreate, clinic: { name: "A" } }).success
    ).toBe(false);
  });

  it("does NOT accept a password: it is generated by the server", () => {
    const r = createClinicSchema.parse({
      ...validCreate,
      doctor: { ...validCreate.doctor, password: "Str0ng!Passw0rd" },
    });
    expect(r.doctor).not.toHaveProperty("password");
  });

  it("validates optional settings", () => {
    expect(
      createClinicSchema.safeParse({
        ...validCreate,
        settings: { appointmentDuration: 2 },
      }).success
    ).toBe(false);
    expect(
      createClinicSchema.safeParse({
        ...validCreate,
        settings: { appointmentDuration: 20, gracePeriod: 10 },
      }).success
    ).toBe(true);
  });

  it("rejects an invalid phone", () => {
    expect(
      createClinicSchema.safeParse({
        ...validCreate,
        clinic: { name: "Al Shifa Clinic", phone: "call me" },
      }).success
    ).toBe(false);
  });
});

describe("listClinicsQuerySchema", () => {
  it("applies defaults", () => {
    expect(listClinicsQuerySchema.parse({})).toEqual({
      status: "all",
      page: 1,
      limit: 20,
    });
  });

  it("coerces numbers and rejects bad values", () => {
    expect(listClinicsQuerySchema.parse({ page: "2", limit: "50" })).toMatchObject({
      page: 2,
      limit: 50,
    });
    expect(listClinicsQuerySchema.safeParse({ limit: "101" }).success).toBe(false);
    expect(listClinicsQuerySchema.safeParse({ status: "banned" }).success).toBe(false);
  });
});

describe("updateClinicSchema", () => {
  it("requires at least one field", () => {
    expect(updateClinicSchema.safeParse({}).success).toBe(false);
  });

  it("allows null to clear optional fields", () => {
    expect(updateClinicSchema.safeParse({ phone: null, address: null }).success).toBe(true);
  });
});

describe("updateClinicStatusSchema", () => {
  it("needs a boolean isActive", () => {
    expect(updateClinicStatusSchema.safeParse({ isActive: false }).success).toBe(true);
    expect(updateClinicStatusSchema.safeParse({ isActive: "no" }).success).toBe(false);
    expect(updateClinicStatusSchema.safeParse({}).success).toBe(false);
  });
});

describe("addDoctorSchema", () => {
  it("accepts a valid doctor and lowercases the email", () => {
    const r = addDoctorSchema.parse({
      fullName: "Dr. Sara",
      email: "SARA@Example.com",
      specialty: "Dermatology",
    });
    expect(r.email).toBe("sara@example.com");
  });

  it("rejects an out-of-range appointment duration", () => {
    expect(
      addDoctorSchema.safeParse({
        fullName: "Dr. Sara",
        email: "sara@example.com",
        specialty: "Dermatology",
        appointmentDuration: 500,
      }).success
    ).toBe(false);
  });
});

describe("params", () => {
  const uuid = "123e4567-e89b-42d3-a456-426614174000";

  it("validates uuids", () => {
    expect(clinicIdParamSchema.safeParse({ id: uuid }).success).toBe(true);
    expect(clinicIdParamSchema.safeParse({ id: "abc" }).success).toBe(false);
    expect(clinicUserParamSchema.safeParse({ id: uuid, userId: uuid }).success).toBe(true);
    expect(clinicUserParamSchema.safeParse({ id: uuid, userId: "x" }).success).toBe(false);
  });
});
